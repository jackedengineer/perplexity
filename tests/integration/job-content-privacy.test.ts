import {afterAll,beforeAll,expect,it} from 'vitest';
import {eq,sql} from 'drizzle-orm';
import {durableJobs,jobCheckpoints,jobPeriods,jobResearchInputs,operatorUsageBuckets} from '@/db/schema';
import {admitJob,listJobs,readJob} from '@/server/jobs/admission';
import {claimJob,startStep,completeStep} from '@/server/jobs/worker';
import {removeJobContent,pruneJobEvidence} from '@/server/jobs/privacy';
import {consumeResearch} from '@/server/deep-research/consumer';
import {jobsFixture} from './jobs-fixture';
import {models,providers} from './deep-fixture';
let f:Awaited<ReturnType<typeof jobsFixture>>;
beforeAll(async()=>{f=await jobsFixture();await f.db.update(operatorUsageBuckets).set({providerLimitMicroUsd:1_000_000n});},30000);
afterAll(()=>f?.pg.close());
const input=()=>({version:1,workflow:'deep-research-v1',requestId:crypto.randomUUID(),question:'Compare SQLite and PostgreSQL for offline applications.',locale:'en'});
it('denies cross-owner deletion, fences active work and keeps accounting after owner deletion',async()=>{
 const raw=input(),id=await admitJob(f.db,f.subject,raw,f.key,models),lease=(await claimJob(f.db,id))!;
 await startStep(f.db,lease,'input');
 await expect(removeJobContent(f.db,'another-owner',id)).rejects.toMatchObject({code:'NOT_FOUND'});
 expect((await readJob(f.db,f.subject,id)).state).toBe('RUNNING');
 await removeJobContent(f.db,f.subject,id);await removeJobContent(f.db,f.subject,id);
 await expect(completeStep(f.db,lease,'input',100n,{allowed:true})).rejects.toMatchObject({code:'STALE'});
 await expect(readJob(f.db,f.subject,id)).rejects.toMatchObject({code:'NOT_FOUND'});
 await expect(admitJob(f.db,f.subject,raw,f.key,models)).rejects.toMatchObject({code:'NOT_FOUND'});
 expect(await listJobs(f.db,f.subject)).toEqual([]);
 expect(await f.db.select().from(jobResearchInputs)).toHaveLength(0);
 expect(await f.db.select().from(jobCheckpoints)).toHaveLength(0);
 expect((await f.db.select().from(durableJobs))[0]).toMatchObject({state:'CANCELLED'});
 expect((await f.db.select().from(durableJobs))[0].deletedAt).toBeInstanceOf(Date);
 expect((await f.db.select().from(operatorUsageBuckets)).every(b=>b.reservedProviderMicroUsd===2250n)).toBe(true);
});
it('prunes old private evidence while retaining the approved exportable report and allowance ledger',async()=>{
 const id=await admitJob(f.db,f.subject,input(),f.key,models);
 expect(await consumeResearch(f.db,id,{providers:providers()})).toBe('COMPLETED');
 const before=await f.db.select().from(jobPeriods);
 await f.db.update(jobCheckpoints).set({createdAt:new Date(Date.now()-2*86400000)}).where(eq(jobCheckpoints.jobId,id));
 expect(await pruneJobEvidence(f.db)).toBeGreaterThan(0);
 expect((await readJob(f.db,f.subject,id)).report?.sections).toHaveLength(3);
 expect((await f.db.select().from(jobCheckpoints)).map(p=>p.step)).toEqual(['publish']);
 await expect(f.db.execute(sql`SELECT perplex_delete_job_content(${id}::uuid,${'another-owner'}::text)`)).resolves.toBeDefined();
 expect((await readJob(f.db,f.subject,id)).report).toBeDefined();
 await removeJobContent(f.db,f.subject,id);
 expect(await f.db.select().from(jobPeriods)).toEqual(before);
 expect(await f.db.select().from(jobCheckpoints)).toHaveLength(0);
});
